"""Merge drafted batches into one draft for author review.

Usage: python -m src.merge_batches <batches_dir> <out.yaml>
Reads batch_A..D.yaml in order and review_flags.yaml (optional reviewer hints), adds an
automatic hint where an RBN and CMR question are nearly identical (weak mixing contrast),
runs item and cross-item checks, and writes the merged draft.
"""
import difflib
import sys
from pathlib import Path

import yaml

from .items import load, validate, validate_set

BATCHES = ("A", "B", "C", "D")
LOW_CONTRAST = 0.97


def main(bdir, out):
    bdir = Path(bdir)
    items = [it for b in BATCHES for it in load(bdir / f"batch_{b}.yaml")]
    flags_path = bdir / "review_flags.yaml"
    flags = yaml.safe_load(flags_path.read_text(encoding="utf-8")) if flags_path.exists() else {}
    for it in items:
        notes = [flags[it["id"]]] if it["id"] in flags else []
        for qname, q in (("main", it["q"]), ("sibling", it["sibling"]["q"])):
            if difflib.SequenceMatcher(None, q["rbn"].lower(), q["cmr"].lower()).ratio() >= LOW_CONTRAST:
                notes.append(f"{qname}: RBN and CMR nearly identical; check CMR has a real English insertion")
        if notes:
            it["review_flag"] = " | ".join(notes)
    problems = validate_set(items) + [p for it in items for p in validate(it)]
    if problems:
        sys.exit("refusing to merge:\n" + "\n".join(problems))
    Path(out).write_text("# AI-drafted new-format items, merged from batches A-D. NOT author-reviewed.\n"
                         "# Generated by src.merge_batches; do not hand-edit.\n"
                         + yaml.safe_dump(items, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(f"merged {len(items)} items, {sum('review_flag' in it for it in items)} flagged -> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
