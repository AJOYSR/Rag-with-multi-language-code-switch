"""Apply the author's returned review sheets to the draft items.

Usage: python -m src.apply_review <draft.yaml> <variants_dir> <approved.yaml> [prefix]
Reads <prefix>_RETURNED.csv and <prefix>_passages_RETURNED.csv (default prefix: review_pilot).
Writes approved.yaml (only items with every row approved or edited, and every
automatic check passing) and review_outcome.json (edit rates, drops, problems).
"""
import csv
import json
import sys
from pathlib import Path

import yaml

from .items import VARIANTS, validate, load


def _rows(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def _status(row):
    s = (row.get("STATUS (approve/edit/drop)") or "").strip().lower()
    return s if s in ("approve", "edit", "drop") else ""


def main(draft, vdir, approved, prefix="review_pilot"):
    vdir = Path(vdir)
    items = {it["id"]: it for it in load(draft)}
    passages = {r["item_id"]: r for r in _rows(vdir / f"{prefix}_passages_RETURNED.csv")}
    questions = _rows(vdir / f"{prefix}_RETURNED.csv")
    report = {"dropped": [], "unreviewed": [], "not_unanswerable": [], "problems": [],
              "edited_passages": 0, "edited_strings": 0, "reviewed_strings": 0}

    for iid, it in items.items():
        p = passages.get(iid)
        if p is None or not _status(p):
            report["unreviewed"].append(iid)
            continue
        if _status(p) == "drop":
            report["dropped"].append(iid)
            continue
        if (p.get("insufficient_really_unanswerable (Y/N)") or "").strip().upper() == "N":
            report["not_unanswerable"].append(iid)
        if p.get("passage_EDIT", "").strip():
            it["passage"] = p["passage_EDIT"].strip() + "\n"
            report["edited_passages"] += 1
        if p.get("replacement_EDIT", "").strip():
            rep = p["replacement_EDIT"].strip()
            it["insuff_replacement"] = "" if rep == "(delete)" else rep
            report["edited_passages"] += 1

    for r in questions:
        it = items.get(r["item_id"])
        if it is None or r["item_id"] in report["dropped"]:
            continue
        if not _status(r):
            report["unreviewed"].append(f"{r['item_id']}:{r['question']}")
            continue
        if _status(r) == "drop":
            report["dropped"].append(f"{r['item_id']}:{r['question']}")
            continue
        target = it["q"] if r["question"] == "main" else it["sibling"]["q"]
        for v in VARIANTS:
            report["reviewed_strings"] += 1
            if r.get(f"{v}_EDIT", "").strip():
                target[v] = r[f"{v}_EDIT"].strip()
                report["edited_strings"] += 1
        it.setdefault("review", {})[r["question"]] = {
            "meaning_equivalent_all": r.get("meaning_equivalent_all (Y/N)", "").strip(),
            "natural": r.get("natural (Y/N)", "").strip(), "comment": r.get("comment", "").strip()}

    blocked = set(report["not_unanswerable"]) | {x.split(":")[0] for x in report["dropped"] + report["unreviewed"]}
    keep = []
    for iid, it in items.items():
        if iid in blocked:
            continue
        probs = validate(it)
        if probs:
            report["problems"] += probs
            continue
        it["status"] = "author-reviewed"
        keep.append(it)
    Path(approved).write_text(
        "# Author-reviewed pilot items (generated by src.apply_review; do not hand-edit)\n"
        + yaml.safe_dump(keep, allow_unicode=True, sort_keys=False), encoding="utf-8")
    report["approved_items"] = [it["id"] for it in keep]
    report["edit_rate_strings"] = report["edited_strings"] / max(report["reviewed_strings"], 1)
    (vdir / f"{prefix}_outcome.json").write_text(json.dumps(report, ensure_ascii=False, indent=2))
    print(json.dumps({k: (len(v) if isinstance(v, list) else v) for k, v in report.items()}, indent=2))


if __name__ == "__main__":
    main(*sys.argv[1:5])
